;; Run from experiments/lean-ir with a separately compiled class directory/jar.
;; Neither the engine nor this classpath belongs to normal Ansatz loading.
(load-file "research/unchanged-program-benchmark.clj")
(load-file "research/java-ir-baseline/repl.clj")
(load-file "research/java-ir-baseline/checks.clj")
(load-file "research/java-ir-baseline/continuation-checks.clj")
(load-file "research/java-ir-baseline/corpus.clj")
(load-file "research/java-ir-baseline/corpus-checks.clj")
(load-file "research/java-ir-baseline/extern-checks.clj")
(load-file "research/java-ir-baseline/scalar-checks.clj")
(load-file "research/java-ir-baseline/main-checks.clj")
(load-file "test/prototype/closed_call_completion_test.clj")
(load-file "test/prototype/resident_executor_test.clj")
(load-file "research/java-ir-baseline/pure-region.clj")
(load-file "research/java-ir-baseline/pure-region-checks.clj")
(load-file "research/java-ir-baseline/pure-provider.clj")
(load-file "research/java-ir-baseline/pure-provider-checks.clj")
(load-file "research/java-ir-baseline/fork-checks.clj")
(load-file "research/checked-delta.clj")
(load-file "research/checked-delta-checks.clj")
(require 'prototype.delta-import-test 'prototype.module-import-test 'prototype.source-import-test
         'prototype.kernel-artifact-test 'prototype.artifact-association-test
         'prototype.artifact-host-test 'prototype.kernel-host-test
         'prototype.source-import-authorization-test 'prototype.resident-artifact-test
         'prototype.resident-frontend-test 'prototype.resident-preparation-test
         'prototype.resident-binding-dependencies-test)
(let [artifact (first *command-line-args*)
      _ (assert artifact "Pass compiled engine directory or jar")
      basis (java-ir-baseline/class-basis artifact)
      _ (assert (identical? (:loader basis) (.getClassLoader ^Class (:class basis)))
                "Engine must come from the isolated artifact loader")
      _ (when (.endsWith ^String artifact ".jar")
          (assert (= "jar" (.getProtocol (.getResource ^Class (:class basis) "Interpreter.class")))
                  "Expected engine class from jar"))
      results [(java-ir-baseline-checks/check! basis)
               (java-ir-baseline-checks/check! (assoc basis :explicit true))
               (java-ir-continuation-checks/check! basis)
               (lean-compatibility-corpus-checks/check! basis)
               (java-ir-extern-checks/check! basis)
               (java-ir-extern-checks/check! (assoc basis :explicit true))
               (java-ir-scalar-checks/check! basis)
               (java-ir-scalar-checks/check! (assoc basis :explicit true))
               (java-ir-main-checks/check! basis)
               (java-ir-main-checks/check! (assoc basis :explicit true))
               (clojure.test/run-tests 'prototype.closed-call-completion-test)
               (clojure.test/run-tests 'prototype.resident-executor-test)
               (java-ir-pure-region-checks/check! basis)
               (java-ir-pure-provider-checks/check! basis)
               (java-ir-fork-checks/check! basis)
               (research.checked-delta-checks/check!)
               (clojure.test/run-tests 'prototype.delta-import-test)
               (clojure.test/run-tests 'prototype.imported-kernel-test)
               (clojure.test/run-tests 'prototype.module-import-test)
               (clojure.test/run-tests 'prototype.source-import-test)
               (clojure.test/run-tests 'prototype.kernel-artifact-test)
               (clojure.test/run-tests 'prototype.artifact-association-test)
               (clojure.test/run-tests 'prototype.artifact-host-test)
               (clojure.test/run-tests 'prototype.kernel-host-test)
               (clojure.test/run-tests 'prototype.source-import-authorization-test)
               (clojure.test/run-tests 'prototype.resident-artifact-test)
               (clojure.test/run-tests 'prototype.resident-frontend-test)
               (clojure.test/run-tests 'prototype.resident-preparation-test)
               (clojure.test/run-tests 'prototype.resident-binding-dependencies-test)]]
  (shutdown-agents)
  (System/exit (if (and (= [9 9 8 6 5 5 6 6 9 9 4 7 9 4 13 12 9 15 11 11 7 9 4 15 7 10 17 8 4] (mapv :test results))
                       (every? #(zero? (+ (:fail %) (:error %))) results)) 0 1)))
