(defn- external-row [name symbol params]
  {:kind "decl" :name name :sourceLocal true :runtime {:role "ordinary"}
   :ir {:extern {:f name :xs params :type "tobject"
                 :ext {:entries [{:standard {:backend (n "all") :fn symbol}}]}}}})

(deftest unsupported-externs-require-explicit-named-research-traps
  (let [root (n "entry") external (n "external")
        candidate (bundle root [(row root [(parameter 1 "tobject" false)] (call-return external [(arg 1)]))
                                (external-row external "never_implemented" [(parameter 1 "tobject" false)])])]
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"Unsupported raw runtime primitive"
          (install/install (m/world {}) candidate)))
    (let [result (install/install (m/world {}) candidate {:research-traps? true})]
      (is (= "never_implemented" (get-in result [:world :functions external :deferred-extern :symbol])))
      (doseq [run (runners (get-in result [:world :functions]))]
        (is (thrown? clojure.lang.ExceptionInfo (run (m/start (:world result) root [42]) 20)))))))

(deftest aliases-cannot-change-protected-target-ownership-or-type
  (let [root (n "newAlias") target (n "protectedTarget")
        param (parameter 1 "tobject" false)
        existing (with-meta {:params [1] :body [:return [:var 1]]}
                   {:runtime-signature {:params [{:ty "tobject" :borrow false}] :return-type "tobject"}})
        candidate (-> (bundle root [(external-row root "guest_export" [param])])
                      (assoc-in [:manifests 0 :exports] [{:symbol "guest_export" :name target}]))
        installed (:world (install/install (m/world {target existing}) candidate))]
    (is (identical? existing (get-in installed [:functions target])))
    (is (= 42 (:result (m/run (m/start installed root [42]) 10))))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"trusted ABI signature"
          (install/install (m/world {target (with-meta existing nil)}) candidate)))
    (doseq [research? [false true]]
      (is (thrown-with-msg? clojure.lang.ExceptionInfo #"signature mismatch"
            (install/install (m/world {target existing})
              (assoc-in candidate [:declarations root :ir :extern :xs 0 :borrow] true)
              {:research-traps? research?}))))
    ;; A forged imported copy is never the authority for an old target's ABI.
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"signature mismatch"
          (install/install (m/world {target existing})
            (-> candidate
                (assoc-in [:declarations target] (assoc (row target [(assoc param :borrow true)] ["ret" (arg 1)]) :sourceLocal false))
                (assoc-in [:declarations root :ir :extern :xs 0 :borrow] true)))))))

(deftest initialization-is-explicit-ordered-and-synthetic-names-are-protected
  (let [root (n "entry") global (n "global") io-name (n "ioAction") io-target (n "ioTarget")
        value-action {:kind "value" :name global :target global}
        io-action {:kind "io" :name io-name :target io-target}
        candidate (-> (bundle root [(row root [] ["ret" "erased"])
                                    (assoc-in (row global [] ["vdecl" {:idx 0} "tobject" {:lit {:v {:num {:v 42}}}} ["ret" (arg 0)]])
                                              [:runtime :role] "closed")
                                    (row io-target [(parameter 0 "void" false)] ["ret" "erased"])])
                      (assoc-in [:manifests 0 :initializationPlan :actions]
                                [{:meta false :action value-action} {:meta false :action io-action}]))
        source-world (m/world {})
        result (install/install source-world candidate)
        world (:world result) pending (:pending-local-initializers result)]
    (is (= (dissoc source-world :functions) (dissoc world :functions)))
    (is (= [value-action io-action] (mapv :completion-key pending)))
    (is (= [global ["str" io-name "_ansatz_io_initializer"]] (mapv :call-target pending)))
    (is (= "closed" (get-in world [:functions global :global-role])))
    (is (= [] (:runtime-param-types (meta (get-in world [:functions global])))))
    (let [done (initialization/finish (m/run (m/start (initialization/begin world) global []) 10))]
      (is (= 42 (:result done)))
      (is (= :ready (get-in done [:globals global :status]))))
    (is (= [value-action] (mapv :completion-key
                              (:pending-local-initializers (install/install source-world candidate {:completed-local-actions #{io-action}})))))
    (doseq [synthetic [["str" global "_ansatz_global_initializer"] ["str" io-name "_ansatz_io_initializer"]]]
      (is (thrown-with-msg? clojure.lang.ExceptionInfo #"name collision"
            (install/install (m/world {synthetic {:params [] :body [:return [:imm 0]]}}) candidate))))))

(deftest initialized-globals-preserve-roles-signatures-and-explicit-init-targets
  (let [root (n "initializedEntry") global (n "initializedGlobal") initializer (n "produceGlobal")
        action {:kind "initialize" :name global :target initializer}
        candidate (-> (bundle root [(row root [] ["ret" "erased"])
                                    (assoc (row global [] ["ret" "erased"])
                                           :runtime {:role "initialized" :initializer initializer})
                                    (row initializer [(parameter 0 "void" false)]
                                         ["vdecl" {:idx 1} "tobject" {:lit {:v {:num {:v 42}}}}
                                          ["vdecl" {:idx 2} "tobject"
                                           {:ctor {:i {:cidx 0 :size 1 :usize 0 :ssize 0} :ys [(arg 1)]}}
                                           ["ret" (arg 2)]]])])
                      (assoc-in [:manifests 0 :initializationPlan :actions] [{:meta false :action action}]))
        installed (install/install (m/world {}) candidate)
        world (:world installed)
        pending (first (:pending-local-initializers installed))
        target ["str" global "_ansatz_global_initializer"]]
    (is (= target (:call-target pending)))
    (is (= target (get-in world [:functions global :init-target])))
    (is (= initializer (get-in world [:functions global :runtime-initializer])))
    (is (= [] (:runtime-param-types (meta (get-in world [:functions global])))))
    (is (empty? (:globals world)))
    (doseq [run (runners (:functions world))]
      (let [done (initialization/finish (run (m/start (initialization/begin world) target []) 100))]
        (is (= 42 (:result done)))
        (is (= {:status :ready :value 42} (get-in done [:globals global])))
        (is (= 42 (:result (run (m/start done global []) 100))))))))

(deftest old-local-io-completion-is-not-inferred-from-the-presence-of-code
  (let [root (n "nextEntry") old-io (n "previousIO")
        action {:kind "io" :name old-io :target old-io}
        candidate (-> (bundle root [(row root [] ["ret" "erased"])])
                      (assoc-in [:manifests 0 :initializationPlan :actions] [{:meta false :action action}]))
        old-f (with-meta {:params [] :body [:unreachable]} {:runtime-param-types []})
        world (m/world {old-io old-f})
        completion-key [:prototype.initialization/io old-io]]
    (is (= [action] (mapv :completion-key (:pending-local-initializers (install/install world candidate)))))
    (is (empty? (:pending-local-initializers
                 (install/install (assoc-in world [:globals completion-key] {:status :ready :value m/erased}) candidate))))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"incomplete prior initialization"
          (install/install (assoc-in world [:globals completion-key] {:status :initializing}) candidate)))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"incomplete prior initialization"
          (install/install (assoc-in world [:globals completion-key] {:status :initializing}) candidate
                           {:completed-local-actions #{action}})))))

