(ns prototype.program-install-test
  (:require [clojure.test :refer [deftest is testing]]
            [prototype.program-install :as install]
            [prototype.machine :as m]
            [prototype.mutable :as u]
            [prototype.block-compile :as blocks]
            [prototype.lazy-runtime :as lazy]
            [prototype.initialization :as initialization]))

(defn- n [s] ["str" ["anonymous"] s])
(def answer (n "answer"))
(def boxed ["str" answer "_boxed"])
(def initial-bundle (delay (install/bundle-catalogue (slurp "fixtures/runtime-compiled-identity.jsonl"))))
(defn- parameter [i ty borrow] {:x {:idx i} :ty ty :borrow borrow})
(defn- arg [i] {:var {:id {:idx i}}})
(defn- row [name params body]
  {:kind "decl" :name name :sourceLocal true :runtime {:role "ordinary"}
   :ir {:fdecl {:f name :xs params :type "tobject" :body body}}})
(defn- bundle [root rows]
  {:manifests [(assoc (first (:manifests @initial-bundle))
                      :requestedRoots [root] :entryPoints [{:name root :boxedTarget root}])]
   :declarations (into {} (map (juxt :name identity)) rows)})
(defn- call-return [target args]
  ["vdecl" {:idx 20} "tobject" {:fap {:c target :ys args}} ["ret" (arg 20)]])
(defn- runners [functions]
  [#(m/run %1 %2)
   #(u/freeze (u/run! (u/thaw %1) %2))
   (let [p (blocks/compile-program functions)] #(u/freeze (blocks/run! p (u/thaw %1) %2)))
   (let [p (lazy/open-program functions)] #(u/freeze (lazy/run! p (u/thaw %1) %2)))])

(deftest native-compiled-identity-installs-and-runs-all-backends
  ;; Generated by pinned RuntimeCompileShim.seededIdentityBundle, not hand IR.
  (let [callback (n "protectedCallback")
        old {callback {:params [0 1] :body [:return [:var 0]]}}
        [world captured] (m/allocate (assoc (m/world old) :environment {"kept" "yes"}
                                          :entropy {:input [1 2 3] :cursor 1}
                                          :initialized-modules #{[(n "Init") :all]}) :ctor 1 [42])
        [world closure] (m/expr world [:closure callback [[:imm captured]]])
        world (assoc-in (m/mark-persistent world closure) [:globals callback] {:status :ready :value closure})
        result (install/install world @initial-bundle)
        installed (:world result)
        functions (:functions installed)]
    (is (= (dissoc world :functions) (dissoc installed :functions)))
    (is (identical? (get old callback) (get functions callback)))
    (is (= {answer boxed} (:boxed-entrypoints result)))
    (is (= #{answer boxed} (set (keys (:new-functions result)))))
    (is (empty? (:pending-local-initializers result)))
    (is (= {:params [{:ty "erased" :borrow false} {:ty "tobject" :borrow true}]
            :return-type "tobject"} (:runtime-signature (meta (get functions answer)))))
    (doseq [run (runners functions) fuel (range 9)]
      (let [start (m/start installed boxed [m/erased 42])
            expected (m/run start fuel) paused (run start fuel)]
        (is (= expected paused))
        (is (= 42 (:result (if (= :paused (:status paused))
                            (run (m/resume paused nil) 100) paused))))))
    ;; Boxed wrapper balances a borrowed callee's increment and its own owned
    ;; argument decrement, so installing does not erase the ownership ABI.
    (let [[world value] (m/resource installed :identity-argument)]
      (doseq [run (runners functions)]
        (let [done (run (m/start world boxed [m/erased value]) 100)]
          (is (= value (:result done)))
          (is (= 1 (:rc (m/node done value)))))))))

(deftest protected-names-remain-protected-even-for-identical-ir
  (let [world (:world (install/install (m/world {}) @initial-bundle))]
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"protected name"
          (install/install world @initial-bundle)))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"protected name"
          (install/install (m/world {}) @initial-bundle {:protected-names #{answer}})))
    (doseq [status [:running :paused :suspended :host-call]]
      (is (thrown-with-msg? clojure.lang.ExceptionInfo #"idle top-level"
            (install/install (assoc (m/world {}) :status status) @initial-bundle))))))

