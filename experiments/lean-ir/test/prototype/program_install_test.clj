(deftest dependency-walk-stops-at-installed-functions-without-reading-backing-catalogue
  (let [root (n "newCaller") dependency (n "installedDependency")
        old-f {:params [1] :body [:return [:var 1]]}
        reads (atom [])
        candidate (-> (bundle root [(row root [(parameter 1 "tobject" false)] (call-return dependency [(arg 1)]))])
                      (assoc-in [:manifests 0 :missingDependencies] [dependency])
                      (assoc-in [:declarations dependency] {:kind "missing" :name dependency}))
        result (install/install (m/world {dependency old-f}) candidate
                                {:catalogue {:manifests [] :declarations {dependency :opaque-index}
                                             :read-declaration (fn [name] (swap! reads conj name)
                                                                 (throw (ex-info "Old body was decoded" {:name name})))}})]
    (is (empty? @reads))
    (is (= #{root} (set (keys (:new-functions result)))))
    (is (identical? old-f (get-in result [:world :functions dependency])))
    (is (= 42 (:result (m/run (m/start (:world result) root [42]) 10))))))

(deftest dependencies-derive-from-bodies-and-can-be-loaded-lazily
  (let [root (n "caller") leaf (n "newDependency")
        root-row (assoc (row root [(parameter 1 "tobject" false)] (call-return leaf [(arg 1)])) :dependencies [])
        dependency (row leaf [(parameter 1 "tobject" false)] ["ret" (arg 1)])
        reads (atom [])
        backing {:manifests (:manifests @initial-bundle) :declarations {leaf :opaque-index}
                 :read-declaration (fn [name] (swap! reads conj name) (when (= leaf name) dependency))}
        candidate (bundle root [root-row])]
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"Missing compiled declaration"
          (install/install (m/world {}) candidate)))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"producer/profile mismatch"
          (install/install (m/world {}) candidate
            {:catalogue (assoc-in backing [:manifests 0 :leanCommit] "other-build")})))
    (reset! reads [])
    (let [installed (:world (install/install (m/world {}) candidate {:catalogue backing}))]
      (is (= [leaf] @reads))
      (is (= 42 (:result (m/run (m/start installed root [42]) 20)))))
    (is (thrown-with-msg? clojure.lang.ExceptionInfo #"arity mismatch"
          (install/install (m/world {leaf {:params [] :body [:return [:imm 42]]}}) candidate)))))

