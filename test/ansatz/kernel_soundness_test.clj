          "inferTypeCore PROJ must compare the projection's structure name with the type head"))))

;; ============================================================
;; #14807 — is_prop via ensure_sort, not whnf-then-syntactic-Sort
;; ============================================================
;;
;; Upstream: `is_prop(e)` was `whnf(infer_type(e)) == Prop`, so when the sort of a type is
;; STUCK (whnf does not reach a Sort) the answer was "not a proposition", and infer_proj then
;; allowed extracting a data field out of a proof. #14807 makes it `ensure_sort(infer_type(e))`,
;; which throws on a stuck sort. The upstream test builds an inductive `Owner (h : P) : gate h`
;; whose sort `gate h` K-reduces to `Prop` for the generic `h` but is stuck for a specific
;; witness `w : a = c` because `a ≢ c` directly (non-transitivity again).
;;
;; Ours: TypeChecker.isProp (TypeChecker.java:555-558) is
;;   `Expr t = whnf(inferTypeOnly(e)); return t.tag == SORT && level.tag == ZERO;`
;; — exactly the pre-fix shape: a stuck sort yields false, and PROJ inference (:957-973) then
;; permits the data projection. Fix: throw when `t` is not a Sort (Lean's ensure_sort) and test
;; the level with `Level.isZero` (normalizing) rather than the syntactic tag.

(defn- with-owner
  "Env extended with the #14807 construction on top of the gadget:
     ksP : Prop := ksA = ksB
     ksGate (h : ksP) : Type := Eq.rec (motive := fun _ _ => Type) Prop h   -- K-reduces to Prop
     inductive KsOwner (h : ksP) : ksGate h | mk (bit : Bool)                -- lives in Prop
     ksAsProp (h : ksP) : Prop := KsOwner h
     axiom ksWitness : ksA = 7                                               -- : ksP up to defeq
     ksProposition : Prop := ksAsProp ksWitness
   The sort of `KsOwner ksWitness` is `ksGate ksWitness`, stuck (ksA ≢ 7 blocks K-reduction)."
  [env]
  (let [eq1 (c "Eq" [l1])
        ksP-val (e/app* eq1 @Nat (c "ksA") (c "ksB"))
        env (admit env (env/mk-def (n "ksP") [] prop ksP-val :hints {:regular 3}))
        eq-rec (c "Eq.rec" (level-args env "Eq.rec" {"u" l2 "u_1" l1}))
        motive (lam "b" @Nat (lam "h" (e/app* eq1 @Nat (c "ksA") (bv 0)) type0))
        gate-body (lam "h" (c "ksP") (e/app* eq-rec @Nat (c "ksA") motive prop (c "ksB") (bv 0)))
        env (admit env (env/mk-def (n "ksGate") [] (e/arrow (c "ksP") type0) gate-body :hints {:regular 4}))
        Owner (n "KsOwner") mk (n "KsOwner.mk")
        env (declare-inductive
             env [] 1
             [(env/mk-induct Owner [] (pi "h" (c "ksP") (e/app (c "ksGate") (bv 0)))
                             :num-params 1 :num-indices 0 :all [Owner] :ctors [mk])]
             [(env/mk-ctor mk [] (pi "h" (c "ksP") (pi "bit" @Bool (e/app (c "KsOwner") (bv 1))))
                           Owner 0 1 1)])
        env (admit env (env/mk-def (n "ksAsProp") [] (e/arrow (c "ksP") prop)
                                   (lam "h" (c "ksP") (e/app (c "KsOwner") (bv 0))) :hints {:regular 5}))
        env (admit env (env/mk-axiom (n "ksWitness") [] (e/app* eq1 @Nat (c "ksA") (lit 7))))
        env (admit env (env/mk-def (n "ksProposition") [] prop
                                   (e/app (c "ksAsProp") (c "ksWitness")) :hints {:regular 6}))]
    env))

(def ^:private owner-env (delay (with-owner @gadget-env)))

(deftest pr14807-owner-fixture-is-a-genuine-proposition
