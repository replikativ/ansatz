;; ============================================================
;; #14577 — arguments to phantom parameters of nesting inductives are type-checked
;; ============================================================
;;
;; Upstream: nested-inductive elimination replaces every nested occurrence `I Ds` by an
;; auxiliary type; the parametric arguments `Ds` are dropped from the auxiliary block, so an
;; ill-typed argument to a PHANTOM parameter (one no constructor mentions) escaped checking.
;; #14577 type-checks each replaced `I Ds` in the final environment.
;;
;; Ours: InductiveBundleChecker.checkBundle (InductiveBundleChecker.java:20-70) — on the nested
;; path it checks the AUX bundle, restores, and calls InductiveChecker.admitOriginalBundle
;; (InductiveChecker.java:362-368), which `addConstant`s the ORIGINAL constructors without ever
;; type-checking their types; NestedInductiveEliminator (:437-460) never type-checks the nested
;; app it replaces. The non-nested path DOES check constructor types (checkConstructors :141-145).

(defn- with-phantom-types
  "KsC (structure with a Bool field), KsW (another one-field type), KsL (α : Type) (b : Bool) : Type
   whose single constructor mentions neither parameter — both are phantom."
  [env]
  (let [decl1 (fn [env nm ty ctor-nm ctor-ty nparams nfields]
                (env/check-inductive-bundle
                 env (env/mk-inductive-bundle
                      [] nparams false
                      [(env/mk-induct (n nm) [] ty :num-params nparams :num-indices 0
                                      :all [(n nm)] :ctors [(n ctor-nm)])]
                      [(env/mk-ctor (n ctor-nm) [] ctor-ty (n nm) 0 nparams nfields)]
                      [])
                 fuel))
        env (decl1 env "KsC" type0 "KsC.mk" (e/arrow @Bool (c "KsC")) 0 1)
        env (decl1 env "KsW" type0 "KsW.mk" (e/arrow @Bool (c "KsW")) 0 1)
        env (decl1 env "KsL" (pi "α" type0 (pi "b" @Bool type0)) "KsL.mk"
                   (pi "α" type0 (pi "b" @Bool (e/app* (c "KsL") (bv 1) (bv 0)))) 2 0)]
    env))

(def ^:private phantom-env (delay (with-phantom-types @E)))

(defn- nesting-bundle
  "inductive KsE (w : KsW) : Type | mk (l : KsL (KsE w) <bad>) : KsE w — `bad` is the argument to
   KsL's phantom Bool parameter. `num-nested` selects the kernel path (Lean always eliminates)."
  [bad num-nested]
  (let [KsE (n "KsE") mk (n "KsE.mk")]
    (env/mk-inductive-bundle
     [] 1 false
     [(env/mk-induct KsE [] (pi "w" (c "KsW") type0)
                     :num-params 1 :num-indices 0 :all [KsE] :ctors [mk] :num-nested num-nested)]
     [(env/mk-ctor mk []
                   (pi "w" (c "KsW")
                       (pi "l" (e/app* (c "KsL") (e/app (c "KsE") (bv 0)) bad)
                           (e/app (c "KsE") (bv 1))))
                   KsE 0 1 1)]
     [])))

(deftest pr14577-control-non-nested-path-checks-the-argument
