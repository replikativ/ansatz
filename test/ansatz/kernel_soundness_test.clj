;; ============================================================
;; #14808 — generated recursors and ι-rules are kernel-checked
;; ============================================================
;;
;; Upstream: `add_core` installed generated recursors unchecked; #14808 adds `check_recursors`:
;; (1) `tc().check(rec_type)`, (2) for every constructor, `lhs := rec params Cs minors indices
;; (ctor params fields)`, `whnf(lhs)` must have a type defeq to `infer(lhs)`.
;;
;; Ours: recursors reach the env only through InductiveBundleChecker. IMPORTED recursors are
;; validated against our generator (RecursorGenerator.checkAndDeclareRecursors :164-175:
;; type and every rule RHS must be structurally equal or defeq to the generated one; existing
;; test `reject-corrupt-imported-recursor-rule-test`) — a stronger check than #14808 for
;; imports. GENERATED recursors (nested aux blocks, InductiveChecker.generateAndCheckRecursors
;; :68-75) only pass checkRecursorDeclaration (TypeChecker.java:2466-2492: the type is a sort,
;; nfields matches) — no ι-rule type-preservation check. So the generator is trusted. The test
;; below applies Lean's check_recursors to our generated recursors for several shapes.

(defn- recursor-rules-type-preserving?
  "Lean #14808's check (2) for `rec-name` in `env`: every ι-rule is type-preserving."
  [env rec-name]
  (let [rec ^ConstantInfo (env/lookup env (n rec-name))
        lps (vec (.levelParams rec))
        tc (fresh-tc env lps)
        fresh! (fn [nm ty] (let [id (.nextFvarId tc)] (.addLocal tc id (str nm) ty) (e/fvar id)))
        peel (fn [ty k]
               (loop [ty ty k k fvs []]
                 (if (zero? k) [fvs ty]
                     (let [fv (fresh! (e/forall-name ty) (e/forall-type ty))]
                       (recur (e/instantiate1 (e/forall-body ty) fv) (dec k) (conj fvs fv))))))
        np (.numParams rec) nmot (.numMotives rec) nmin (.numMinors rec)
        [pre _] (peel (.type rec) (+ np nmot nmin))
        params (subvec pre 0 np)
        motives (subvec pre np (+ np nmot))
        minors (subvec pre (+ np nmot))
        rec-const (e/const' (n rec-name) (mapv lvl/param lps))]
    (every? (fn [^ConstantInfo$RecursorRule rule]
              (let [ctor ^ConstantInfo (env/lookup env (.ctor rule))
                    ctor-const (e/const' (.ctor rule) (mapv lvl/param (vec (.levelParams ctor))))
                    cty (reduce (fn [ty p] (e/instantiate1 (e/forall-body ty) p)) (.type ctor) params)
                    [fields res] (peel cty (.nfields rule))
                    indices (vec (drop np (e/get-app-args res)))
                    lhs (apply e/app* rec-const
                               (concat params motives minors indices
                                       [(apply e/app* ctor-const (concat params fields))]))
                    expected (.check tc lhs)
                    reduct (tc-whnf tc lhs)]
                (and (not (identical? reduct lhs))
                     (.isDefEq tc (.inferType tc reduct) expected))))
            (.rules rec))))

(deftest pr14808-generated-recursors-are-type-preserving
  (testing "Lean's check_recursors holds for our generated recursors (KsAc: large-eliminating
   predicate with an IH; KsOwner: Prop-only elimination with a data field) and for imported ones
   (Nat, List, Acc, Eq with K)"
    (let [env @owner-env]
      (doseq [r ["KsAc.rec" "KsOwner.rec" "Nat.rec" "List.rec" "Acc.rec" "Eq.rec"]]
        (is (recursor-rules-type-preserving? env r) r)))))

