(ns ansatz.kernel-soundness-test
  "Audit of the Java kernel against the Lean 4 kernel soundness fixes that landed upstream
   between March and August 2026 (issue #77). One section per upstream PR. Every section pins
   the invariant the PR establishes; where our kernel is still exposed the test is `^:wip`
   (the suite excludes `:wip`), encodes the concrete unsound input, and names the PR — so the
   exposure is tracked by a test that turns green when the kernel is fixed.

   All fixtures are built through the kernel's own admission paths (`check-constant`,
   `check-inductive-bundle`) over the bundled Init tier; nothing here needs Mathlib.

   Shared gadget (used by #14806 and #14807): definitional equality in the kernel is a sound
   but INCOMPLETE semi-decision procedure and therefore NOT transitive. Proof irrelevance makes
   `ksF ax ≡ ksF (KsAc.intro 0 axAll)` (both arguments are proofs of `KsAc 0`); iota makes
   `ksF (KsAc.intro 0 axAll) ≡ 7`; but `ksF ax` is stuck on the axiom, so `ksF ax ≢ 7`. With
   `ksA := ksF ax` and `ksB := ksF (KsAc.intro 0 axAll)`: ksA ≡ ksB, ksB ≡ 7, ksA ≢ 7. This is
   the same shape upstream's `kernel_is_def_eq_equiv_manager_*.lean` tests use (there with
   `Acc.rec` and an opaque accessibility proof)."
  (:require [clojure.test :refer [deftest testing is]]
            [ansatz.test-env :as te]
            [ansatz.kernel.env :as env]
            [ansatz.kernel.expr :as e]
            [ansatz.kernel.level :as lvl]
            [ansatz.kernel.name :as name]
            [ansatz.export.parser :as parser]
            [ansatz.export.replay :as replay])
