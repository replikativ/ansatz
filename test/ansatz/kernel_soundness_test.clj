    (is (nil? (rejection env good)))
    (is (= (lit 1) (whnf env (e/proj (n "Prod") 0 (prod-pair)))))))

(deftest pr14631-projection-structure-name-must-match
  (testing "upstream leanprover/lean4#14631 (and infer_proj) — `(Prod.mk 1 2).proj Bool 0` names
   a structure that is not the type of the projected term and must be an invalid projection"
