(def ^:private fuel 5000000)

(defn- n [s] (name/from-string s))
(defn- c
  ([s] (e/const' (n s) []))
  ([s lvls] (e/const' (n s) lvls)))
(def ^:private l0 lvl/zero)
(def ^:private l1 (lvl/succ lvl/zero))
(def ^:private l2 (lvl/succ l1))
(def ^:private prop (e/sort' l0))
(def ^:private type0 (e/sort' l1))
(defn- pi [nm dom body] (e/forall' nm dom body :default))
(defn- lam [nm dom body] (e/lam nm dom body :default))
(defn- lit [k] (e/lit-nat k))
(defn- bv [i] (e/bvar i))

(def ^:private E (delay @te/bundled-init-env))

(defn- admit
  "check-constant; returns the new env."
  [env ci]
  (env/check-constant env ci fuel))

(defn- rejection
  "The kernel's error message if `ci` is rejected, nil if it is admitted."
  [env ci]
  (try (env/check-constant env ci fuel) nil
       (catch Throwable ex (or (.getMessage ex) (str ex)))))

(defn- bundle-rejection
  [env bundle]
  (try (env/check-inductive-bundle env bundle fuel) nil
       (catch Throwable ex (or (.getMessage ex) (str ex)))))

(defn- fresh-tc
  (^TypeChecker [env] (doto (TypeChecker. env) (.setFuel fuel)))
  (^TypeChecker [env lps]
   ;; safety byte 0 = safe (TypeChecker.DEFN_SAFE is package-private)
   (doto (TypeChecker. env (byte 0) (into-array Object lps)) (.setFuel fuel))))

(defn- whnf [env ex] (.whnf (Reducer. env) ex))

(defn- tc-whnf
  "TypeChecker.whnfExpr (package-private): whnf in the checker's own local context."
  [^TypeChecker tc ex]
  (let [m (doto (.getDeclaredMethod TypeChecker "whnfExpr" (into-array Class [Expr]))
            (.setAccessible true))]
    (.invoke m tc (object-array [ex]))))

(defn- declare-inductive
  "Admit a (non-nested) inductive block through the kernel. A bundle without recursors gets
   none generated by `checkInductiveBundle` (it only VALIDATES imported recursors against the
   generator), so generate them first with the kernel's own generator — the path nested
   inductives take (InductiveChecker.generateAndCheckRecursors) — then admit the full bundle,
   which re-validates the generated recursors exactly as it would imported ones."
  [env lps nparams inds ctors]
  (let [bundle0 (env/mk-inductive-bundle lps nparams false inds ctors [])
        klass (Class/forName "ansatz.kernel.InductiveChecker")
        ctor (doto (.getDeclaredConstructor klass (into-array Class [Env InductiveBundle Long/TYPE]))
               (.setAccessible true))
        ic (.newInstance ctor (object-array [env bundle0 (long fuel)]))
        m (doto (.getDeclaredMethod klass "generateAndCheckRecursors" (into-array Class []))
            (.setAccessible true))
        recs (vec (.invoke m ic (object-array [])))]
    (env/check-inductive-bundle env (env/mk-inductive-bundle lps nparams false inds ctors recs) fuel)))

(defn- level-args
  "Universe arguments for constant `s` in the order of its declared level params, from a
   name→Level map (so tests do not hard-code Lean's level-parameter ordering)."
  [env s m]
  (mapv (fn [p] (get m (str p))) (.levelParams ^ConstantInfo (env/lookup env (n s)))))

