(def ^:private Nat (delay (c "Nat")))
(def ^:private Bool (delay (c "Bool")))

(defn- ksac-ctor-type []
  ;; KsAc.intro : (n : Nat) → (h : (m : Nat) → KsAc m) → KsAc n
  (pi "n" @Nat
      (pi "h" (pi "m" @Nat (e/app (c "KsAc") (bv 0)))
          (e/app (c "KsAc") (bv 1)))))

(defn- with-gadget
  "Env extended with KsAc (an inductive predicate with large elimination, like Acc), the
   axioms, and the definitions ksF / ksA / ksB / ksG."
  [env]
  (let [KsAc (n "KsAc") intro (n "KsAc.intro")
        env (declare-inductive
             env [] 0
             [(env/mk-induct KsAc [] (pi "n" @Nat prop)
                             :num-params 0 :num-indices 1 :all [KsAc] :ctors [intro] :rec? true)]
             [(env/mk-ctor intro [] (ksac-ctor-type) KsAc 0 0 2)])
        ksac0 (e/app (c "KsAc") (lit 0))
        env (admit env (env/mk-axiom (n "ksAx") [] ksac0))
        env (admit env (env/mk-axiom (n "ksAxAll") [] (pi "m" @Nat (e/app (c "KsAc") (bv 0)))))
        env (admit env (env/mk-axiom (n "ksG") [] (e/arrow @Nat @Nat)))
        ;; ksF (h : KsAc 0) : Nat := KsAc.rec.{1} (fun n _ => Nat) (fun n h ih => 7) 0 h
        motive (lam "n" @Nat (lam "t" (e/app (c "KsAc") (bv 0)) @Nat))
        minor (lam "n" @Nat
                   (lam "h" (pi "m" @Nat (e/app (c "KsAc") (bv 0)))
                        (lam "ih" (pi "m" @Nat @Nat) (lit 7))))
        ksF-body (lam "h" ksac0 (e/app* (c "KsAc.rec" [l1]) motive minor (lit 0) (bv 0)))
        env (admit env (env/mk-def (n "ksF") [] (e/arrow ksac0 @Nat) ksF-body :hints {:regular 1}))
        env (admit env (env/mk-def (n "ksA") [] @Nat (e/app (c "ksF") (c "ksAx")) :hints {:regular 2}))
        env (admit env (env/mk-def (n "ksB") [] @Nat
                                   (e/app (c "ksF") (e/app* (c "KsAc.intro") (lit 0) (c "ksAxAll")))
                                   :hints {:regular 2}))]
    env))

(def ^:private gadget-env (delay (with-gadget @E)))

(deftest gadget-is-non-transitive
  (testing "the fixture behaves as designed: ksA ≡ ksB, ksB ≡ 7, but ksA ≢ 7 (each on a FRESH checker)"
    (let [env @gadget-env]
      (is (.isDefEq (fresh-tc env) (c "ksA") (c "ksB")) "proof irrelevance under the same-definition argument shortcut")
      (is (.isDefEq (fresh-tc env) (c "ksB") (lit 7)) "iota on the constructor argument")
      (is (not (.isDefEq (fresh-tc env) (c "ksA") (lit 7))) "stuck on the axiom — not defeq")
      (is (not (.isDefEq (fresh-tc env)
                         (e/app (lam "x" @Nat (e/app (c "ksG") (bv 0))) (c "ksA"))
                         (e/app (c "ksG") (lit 7))))
          "congruence over ksA vs 7 is false on a fresh checker"))))

;; ============================================================
;; #14806 — is_def_eq caching must be order-independent
;; ============================================================
;;
;; Upstream: the union-find `equiv_manager` recorded successful is_def_eq pairs and returned
;; true for any two members of the same class — i.e. it took the TRANSITIVE closure. Since
;; is_def_eq is not transitive, the answer to a query then depended on which pairs had been
;; asked before. #14806 deletes equiv_manager and replaces it with a plain pair-keyed success
;; cache (`m_success`, `succeeded_before`/`cache_success`), symmetric to `m_failure`.
;;
;; Ours: TypeChecker.isDefEq (TypeChecker.java:1068-1079) calls `eqvManager.addEquiv(t, s)`
;; on every success, and quickIsDefEq (:1129-1133) consults `eqvManager.isEquiv`, which
;; MERGES classes as it recurses (EquivManager.java:96-152, `if (result) merge(r1, r2)`).
;; That is the pre-#14806 design verbatim. The identity/structural failure caches
;; (:1812-1856) are pair-keyed and fine; the exposure is the positive cache.

(deftest ^:wip pr14806-defeq-cache-is-order-independent
  (testing "upstream leanprover/lean4#14806 — after ksA ≡ ksB and ksB ≡ 7 were recorded on ONE
   checker, `ksG ksA =?= ksG 7` must still be false (a fresh checker says false). The beta redex
   on the left forces the post-whnf_core quick check (use_hash=false), which walks the two
   applications structurally and finds ksA and 7 in the same union-find class."
    (let [env @gadget-env
          tc (fresh-tc env)
          t (e/app (lam "x" @Nat (e/app (c "ksG") (bv 0))) (c "ksA"))
          s (e/app (c "ksG") (lit 7))]
      (is (.isDefEq tc (c "ksA") (c "ksB")))
      (is (.isDefEq tc (c "ksB") (lit 7)))
      (is (not (.isDefEq tc t s))
          "EXPOSED: transitive closure through the equiv manager (fix: pair-keyed success cache)"))))

;; ============================================================
;; #14631 — projection defeq compares the structure name
;; ============================================================
;;
;; Upstream: is_def_eq_core's proj/proj case and equiv_manager compared only the field index
;; and the projected expression; #14631 adds `proj_sname(t) == proj_sname(s)`. Per lean4lean's
;; divergences.md the comparison is redundant ONLY because `infer_proj` already rejects
;; `.proj S i e` unless the type of `e` whnfs to an application of `S` itself
;; (type_checker.cpp:278-280, `if (I_name != proj_sname(e)) throw invalid_proj_exception`).
;;
;; Ours (before this audit): the PROJ case of inferTypeCore (TypeChecker.java:929-976) took the
;; inductive from the whnf'd type head and NEVER compared it against the projection's own
;; structure name `e.o0`; Step 5b of isDefEqCoreImpl (:1361) compares only `longVal`; EquivManager
;; PROJ (:129-132) explicitly ignores the name. FIXED here with Lean's one-line infer_proj check
;; (TypeChecker.java PROJ case: `if (!head.o0.equals(e.o0)) throw`). With that guard every
;; projection that reaches isDefEq / EquivManager has been through inference, so — exactly as
;; lean4lean argues — the name comparison in the defeq paths is redundant and left as is.

(defn- prod-pair []
  (e/app* (c "Prod.mk" [l0 l0]) @Nat @Nat (lit 1) (lit 2)))

(deftest pr14631-well-named-projection-is-accepted
