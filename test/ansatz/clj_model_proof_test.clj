(ns ansatz.clj-model-proof-test
  "PR G4: proof support for the Clojure model — the `clj_model` simp set (constructor lemmas
   generated by kernel evaluation, dec_enc lemmas), `(a/conforms f)` without a script, the
   :ported path, the paranoid runtime and the trust report."
  (:require [clojure.test :refer [deftest is testing use-fixtures]]
            [ansatz.core :as a]
            [ansatz.fixtures :as fixtures]
            [ansatz.attrs :as attrs]
            [ansatz.clj-check :as cc]
            [ansatz.clj-model :as m]
            [ansatz.clj-model.boundary :as b]
            [ansatz.clj-model.proof :as pf]
            [ansatz.codegen :as cg]
            [ansatz.state :as state]
            [ansatz.surface.data :as data]
            [ansatz.kernel.env :as env]
            [ansatz.kernel.expr :as e]
            [ansatz.kernel.name :as name]))

(def corpus
  "Scalar functions: [name params ret source conforms?]. The conforming ones are proved by the
   default script; the others are not (each has a witness: overflow, or nil for an Int)."
  '[[pc-clamp [x :- Int, lo :- Int, hi :- Int] Int (fn [x lo hi] (cond (< x lo) lo (> x hi) hi :else x)) true]
    [pc-sign [x :- Int] Int (fn [x] (cond (pos? x) 1 (neg? x) -1 :else 0)) true]
    [pc-max2 [a :- Int, b :- Int] Int (fn [a b] (if (> a b) a b)) true]
    [pc-andnot [a :- Bool, b :- Bool] Bool (fn [a b] (and a (not b))) true]
    [pc-or [a :- Bool, b :- Bool] Bool (fn [a b] (or a b)) true]
    [pc-same [s :- String, t :- String] String (fn [s t] (if (= s t) "same" s)) true]
    [pc-bounded [x :- Int] Int (fn [x] (if (< x 100) (if (> x -100) (* 2 x) 0) 0)) true]
    [pc-small-inc [x :- Int] Int (fn [x] (if (and (< x 1000) (> x -1000)) (inc x) x)) true]
    [pc-nat1 [n :- Nat] Nat (fn [n] (if (zero? n) 1 n)) true]
    [pc-nat-dec [n :- Nat] Nat (fn [n] (if (pos? n) (dec n) 0)) true]
    [pc-pick [b :- Bool, x :- Int, y :- Int] Int (fn [b x y] (if b x y)) true]
    [pc-nz [x :- Int] Bool (fn [x] (not= x 0)) true]
    [pc-inrange [x :- Int, lo :- Int] Bool (fn [x lo] (and (>= x lo) (<= x 100))) true]
    [pc-when-pos [x :- Int] Int (fn [x] (if-let [y (when (pos? x) x)] y 0)) true]
    [pc-mapq [m :- Value] Bool (fn [m] (map? m)) true]
    [pc-count [m :- Value] Int (fn [m] (if (map? m) (count m) 0)) true]
    [pc-abs [x :- Int] Int (fn [x] (if (neg? x) (- x) x)) false]
    [pc-succ [x :- Int] Int (fn [x] (+ x 1)) false]
    [pc-when [x :- Int] Int (fn [x] (when (pos? x) x)) false]])

(defn- define-corpus! []
  (doseq [[n params ret f _] corpus]
    (eval `(a/foreign ~(vary-meta n assoc :model true) ~params ~ret ~f))))

(defn- setup [f]
  (binding [a/*verbose* false]
    (a/load-init!)
    (data/install-value-type!)
    (b/install-codecs!)
    (binding [*ns* (the-ns 'ansatz.clj-model-proof-test)]
      (define-corpus!)
      (eval '(ansatz.core/foreign ^:model pc-port [x :- Int] Int (fn [x] (cond (pos? x) 1 (neg? x) -1 :else 0))))
      (eval '(ansatz.core/defn pc-port-dsl [x :- Int] Int (if (> x 0) 1 (if (< x 0) -1 0))))
      (eval '(ansatz.core/defn pc-use-port [x :- Int] Int (+ (pc-port x) 1)))
      (eval '(ansatz.core/foreign ^:model ^:paranoid pc-paranoid [x :- Int] Int (fn [x] (+ x 1)))))
    (f)))

(use-fixtures :once fixtures/isolated-session setup)

(defn- lookup [n] (env/lookup (a/env) (name/from-string n)))

(defn- conforms! [f]
  (try (binding [a/*verbose* false] (b/prove-conforms! f [])) (catch Exception _ :open)))

;; ── Named simp sets ─────────────────────────────────────────────────────────────────────

(deftest a-simp-set-name-means-its-members
  (binding [a/*verbose* false]
    (a/defn pc-twice [n :- Nat] Nat (+ n n))
    (swap! state/ansatz-env attrs/add-to-simp-set "pc_set" ["pc-twice"])
    (is (= ["pc-twice"] (attrs/simp-set (a/env) "pc_set")))
    (is (nil? (attrs/simp-set (a/env) "no_such_set")))
    (a/prove-theorem 'pc-twice-two [] '(= Nat (pc-twice 2) 4) '[(simp [pc_set])])
    (is (some? (lookup "pc-twice-two")))))

;; ── The clj_model simp set ──────────────────────────────────────────────────────────────

(deftest constructor-lemmas-by-kernel-evaluation
  (pf/prepare! "pc-clamp.clj" (:codecs (b/info 'pc-clamp)) (:ret-codec (b/info 'pc-clamp)))
  (let [members (set (attrs/simp-set (a/env) pf/simp-set))
        stmt (fn [n] (e/->string (.type ^ansatz.kernel.ConstantInfo (lookup n))))]
    (testing "one lemma per op and constructor pattern, refined only where the op is stuck"
      (is (re-find #"CljM.lt \(CljM.V.vlong #1\) \(CljM.V.vlong #0\)\) \(Option.some.*CljM.V.vbool"
                   (stmt "CljM.lt.ctor_vlong_vlong")))
      (is (re-find #"\(CljM.lt CljM.V.vnil #0\) \(Option.none" (stmt "CljM.lt.ctor_vnil_x"))
          "the second argument is not refined where the first decides")
      (is (re-find #"CljM.truthy \(CljM.V.vbool #0\)\) #0" (stmt "CljM.truthy.ctor_vbool")))
      (is (re-find #"CljM.encInt #0\) \(CljM.V.vlong #0\)" (stmt "CljM.encInt.ctor_x"))
          "an encoder's lemma unfolds it to its constructor"))
    (testing "the lemmas are theorems in the clj_model set"
      (doseq [n ["CljM.lt.ctor_vlong_vlong" "CljM.gt.ctor_vlong_vlong" "CljM.decInt.ctor_vlong"]]
        (is (.isThm ^ansatz.kernel.ConstantInfo (lookup n)) n)
        (is (contains? members n) n)))
    (testing "dec (enc x) = some x for the scalar codecs"
      (is (contains? members "CljM.decInt_encInt")))))

(deftest equality-goes-through-its-fuel
  (pf/prepare! "pc-same.clj" (:codecs (b/info 'pc-same)) (:ret-codec (b/info 'pc-same)))
  (is (re-find #"CljM.eq \(CljM.V.vstr #1\) \(CljM.V.vstr #0\)\) \(Option.some.*Decidable.decide \(Eq.\{1\} String #1 #0\)"
               (e/->string (.type ^ansatz.kernel.ConstantInfo (lookup "CljM.eq.ctor_vstr_vstr"))))))

(deftest dec-enc-round-trips
  (pf/prepare! "pc-nat1.clj" (:codecs (b/info 'pc-nat1)) (:ret-codec (b/info 'pc-nat1)))
  (pf/prepare! "pc-mapq.clj" (:codecs (b/info 'pc-mapq)) (:ret-codec (b/info 'pc-mapq)))
  (is (some? (lookup "CljM.decNat_encNat")))
  (is (some? (lookup "CljM.decBool_encBool")))
  (is (nil? (lookup "CljM.toValue?_ofValue")) "Value's round trip is not the identity: no lemma"))

;; ── a/conforms without a script ──────────────────────────────────────────────────────────

(deftest default-script-proves-the-conforming-corpus
  (doseq [[f _ _ _ conforms?] corpus]
    (testing (str f)
      (is (= (if conforms? :proved :open) (conforms! f)))
      (is (= (if conforms? :proved :tested) (b/status f)))
      (when conforms?
        (is (some? (lookup (str f ".spec"))) "f.spec from the generic lemma")))))

(deftest proved-agrees-with-testing
  ;; :proved claims the model answers on every input of the declared types; check-model! samples
  ;; them. A proved function the sampler finds a witness against would be a soundness bug.
  (doseq [[f _ _ _ conforms?] corpus]
    (is (= (if conforms? :conforming :nonconforming) (:status (cc/check-model! f :runs 30))) (str f))))

;; ── :ported ──────────────────────────────────────────────────────────────────────────────

(deftest porting-swaps-in-the-dsl-function
  (is (= :clj-model/not-proved
         (:kind (try (b/port! 'pc-port 'pc-port-dsl nil []) nil
                     (catch clojure.lang.ExceptionInfo ex (ex-data ex)))))
      "porting needs :proved first")
  (is (= :proved (conforms! 'pc-port)))
  (binding [a/*verbose* false]
    (is (= :ported (b/port! 'pc-port 'pc-port-dsl @(resolve 'ansatz.clj-model-proof-test/pc-port-dsl) []))))
  (is (= :ported (b/status 'pc-port)))
  (is (some? (lookup "pc-port.ported")))
  (is (= "pc-port-dsl" (get (env/get-extension (a/env) :csimp {}) "pc-port")))
  (let [code (cg/ansatz->clj (a/env) (.value ^ansatz.kernel.ConstantInfo (lookup "pc-use-port")) [])
        syms (set (filter symbol? (tree-seq coll? seq code)))]
    (is (contains? syms 'ansatz.clj-model-proof-test/pc-port-dsl) "compiled code calls the port"))
  (let [f @(resolve 'ansatz.clj-model-proof-test/pc-port)]
    (is (= [1 -1 0] [(f 5) (f -3) (f 0)]) "the runtime is the port"))
  (is (= {"pc-port" :ported} (:modelled (pf/trust-report 'pc-use-port)))))

;; ── :paranoid ────────────────────────────────────────────────────────────────────────────

(deftest paranoid-runtime-compares-impl-and-model
  (let [f @(resolve 'ansatz.clj-model-proof-test/pc-paranoid)
        {:keys [model-fn]} (b/info 'pc-paranoid)]
    (is (= 6 (f 5)) "impl and model agree")
    (is (thrown? ArithmeticException (f Long/MAX_VALUE)) "no claim: the impl's behaviour stands")
    (is (= 6 (b/paranoid-call "pc-paranoid" (fn [x] (+ x 1)) model-fn [5])))
    (let [data (try (b/paranoid-call "pc-paranoid" (fn [x] (+ x 2)) model-fn [5]) nil
                    (catch clojure.lang.ExceptionInfo ex (ex-data ex)))]
      (is (= :clj-model/model-disagrees (:kind data)))
      (is (= [6 7] [(:model data) (:result data)])))
    (let [data (try (b/paranoid-call "pc-paranoid" (fn [_] (throw (ArithmeticException. "x"))) model-fn [5]) nil
                    (catch clojure.lang.ExceptionInfo ex (ex-data ex)))]
      (is (= "java.lang.ArithmeticException" (:threw data)) "the model claims a value where the impl throws"))
    (is (false? (b/paranoid! 'pc-paranoid false)))
    (is (= 6 (f 5)))))

;; ── Trust report ─────────────────────────────────────────────────────────────────────────

(deftest trust-report-shows-tested-dependencies
  (binding [a/*verbose* false *ns* (the-ns 'ansatz.clj-model-proof-test)]
    (eval '(ansatz.core/foreign ^:model pc-tr-succ [x :- Int] Int (fn [x] (+ x 1))))
    (eval '(ansatz.core/foreign ^:model pc-tr-clamp [x :- Int] Int (fn [x] (if (> x 10) 10 x))))
    (eval '(ansatz.core/foreign pc-tr-axiom [x :- Int] Int (fn [x] x)))
    (eval '(ansatz.core/defn pc-tr-use [x :- Int] Int (+ (pc-tr-succ x) (+ (pc-tr-clamp x) (pc-tr-axiom x)))))
    (a/prove-theorem 'pc-tr-thm '[x :- Int] '(= Int (pc-tr-use x) (pc-tr-use x)) '[(rfl)]))
  (let [r (a/trust-report pc-tr-thm)]
    (is (= {"pc-tr-clamp" :tested "pc-tr-succ" :tested} (:modelled r)))
    (is (= ["pc-tr-clamp" "pc-tr-succ"] (:tested r)))
    (is (= ["pc-tr-axiom"] (:other (:axioms r))) "a plain a/foreign is an axiom"))
  (is (= :proved (conforms! 'pc-tr-clamp)))
  (is (= ["pc-tr-succ"] (:tested (a/trust-report pc-tr-thm))) "pc-tr-succ does not conform: it stays :tested"))

;; ── Fixes the default script needed ──────────────────────────────────────────────────────

(deftest negative-int-literals-in-comparisons-are-int-literals
  ;; `(<= -9223372036854775808 i)` in a Bool position: an Int literal is `Int.ofNat k` or
  ;; `Int.negSucc k` with k natural; a negative Nat literal inside `Int.ofNat` is not one
  (let [lits (volatile! [])]
    (letfn [(walk [x] (case (e/tag x)
                        :lit-nat (vswap! lits conj (e/lit-nat-val x))
                        :app (do (walk (e/app-fn x)) (walk (e/app-arg x)))
                        :lam (do (walk (e/lam-type x)) (walk (e/lam-body x)))
                        nil))]
      (walk (.value ^ansatz.kernel.ConstantInfo (lookup "CljM.inLong"))))
    (is (seq @lits))
    (is (every? #(not (neg? %)) @lits))))

(deftest omega-handles-long-min
  ;; reconstructing the constant -2^63 negated it as a long (overflow)
  (binding [a/*verbose* false]
    (a/prove-theorem 'pc-omega-min '[x :- Int, h1 :- (< -100 x),
                                     h :- (Not (<= (Int.negSucc 9223372036854775807) (* 2 x)))]
                     'False '[(omega)]))
  (is (some? (lookup "pc-omega-min"))))

(deftest repeat-tactic
  (binding [a/*verbose* false]
    (a/prove-theorem 'pc-repeat '[p :- Prop, q :- Prop, hp :- p, hq :- q] '(And p (And p q))
                     '[(repeat (any_goals (constructor))) (all_goals (assumption))]))
  (is (some? (lookup "pc-repeat"))))
