#!/usr/bin/env python3
"""Plan one guarded javac build from a frozen committed source capture.

Never invokes Java/javac/native tools. Source capture and dependency/JDK pins
must come from the independently reviewed guard inputs. Generated bytes are
build observations, not an accepted consumer contract or loaded-code evidence.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import maven_basis


def digest(path):
    # Python 3.10 is used by component CI; keep bounded streaming portable.
    result = hashlib.sha256()
    with Path(path).open("rb") as stream:
        while block := stream.read(1024 * 1024):
            result.update(block)
    return result.hexdigest()


def quoted(value):
    value = str(value)
    if any(c in value for c in "\r\n\x00"):
        raise ValueError("javac argument control character")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--capture", type=Path, required=True)
    p.add_argument("--expected-capture-sha256", required=True)
    p.add_argument("--jdk", type=Path, required=True)
    p.add_argument("--expected-release-sha256", required=True)
    p.add_argument("--dependency", action="append", required=True, help="PATH=EXTERNAL_SHA256")
    p.add_argument("--dependency-lock", type=Path)
    p.add_argument("--expected-dependency-lock-sha256")
    args = p.parse_args()
    if bool(args.dependency_lock) != bool(args.expected_dependency_lock_sha256):
        raise ValueError("dependency lock and independent digest required together")
    basis = (maven_basis.load(args.dependency_lock, args.expected_dependency_lock_sha256)
             if args.dependency_lock else None)
    if basis is not None and args.dependency != [row["path"] + "=" + row["sha256"] for row in basis["dependencies"]]:
        raise ValueError("dependency arguments must exactly match isolated lock order")
    root = args.capture.resolve(strict=True)
    capture_file = root / "source-capture.json"
    if digest(capture_file) != args.expected_capture_sha256:
        raise ValueError("source capture external digest mismatch")
    capture = json.loads(capture_file.read_text())
    if capture["schema"] != "coherent-source-capture/1":
        raise ValueError("wrong source capture schema")
    source = root / "selected"
    actual = {str(path.relative_to(source)) for path in source.rglob("*") if path.is_file()}
    expected = {row["id"] for row in capture["inputs"]}
    if actual != expected:
        raise ValueError("source capture extra/missing file")
    for row in capture["inputs"]:
        path = source / row["id"]
        if path.is_symlink() or digest(path) != row["sha256"] or path.stat().st_size != row["bytes"]:
            raise ValueError("source capture drift: " + row["id"])
    jdk = args.jdk.resolve(strict=True)
    if digest(jdk / "release") != args.expected_release_sha256:
        raise ValueError("JDK release external pin mismatch")
    release = dict(line.split("=", 1) for line in (jdk / "release").read_text().splitlines() if "=" in line)
    if not release.get("JAVA_VERSION", "").strip('"').startswith("25"):
        raise ValueError("this reviewed build recipe requires JDK 25")
    build = root / "java-build-plan"
    if build.exists() or (root / "classes").exists() or (root / "dependencies").exists():
        raise ValueError("build plan/dependency/class roots must be new")
    build.mkdir()
    (root / "classes").mkdir()
    (root / "dependencies").mkdir()
    dependencies = []
    names = set()
    for spec in args.dependency:
        raw, expected_hash = spec.rsplit("=", 1)
        path = Path(raw).resolve(strict=True)
        if path.name in names or digest(path) != expected_hash:
            raise ValueError("dependency duplicate name/external pin mismatch")
        names.add(path.name)
        target = root / "dependencies" / path.name
        shutil.copyfile(path, target)
        if digest(target) != expected_hash:
            raise ValueError("dependency copy drift")
        dependencies.append({"id": "dependencies/" + path.name, "path": "dependencies/" + path.name,
                             "sha256": expected_hash})
    if basis is None and (not any("clojure-1.12.0" in n for n in names) or not any("data.json-2.5.1" in n for n in names)):
        raise ValueError("explicit Clojure 1.12.0/data.json 2.5.1 dependency jars required")
    java_ids = sorted(row["id"] for row in capture["inputs"] if row["id"].endswith(".java"))
    if "java/prototype/TypedLongMemo.java" not in java_ids:
        raise ValueError("TypedLongMemo Java source missing")
    arguments = ["-source", "11", "-target", "11", "-cp",
                 ":".join(str(root / row["path"]) for row in dependencies),
                 "-d", str(root / "classes")] + [str(source / x) for x in java_ids]
    (build / "javac.args").write_text("\n".join(map(quoted, arguments)) + "\n")
    record = {"schema": "coherent-java-build-plan/1", "status": "PLAN_ONLY_NOT_COMPILED",
              "commit": capture["commit"], "capture-sha256": args.expected_capture_sha256,
              "source-root": "selected", "class-root": "classes", "java-source-ids": java_ids,
              "jdk": {"runtime-version": release.get("JAVA_RUNTIME_VERSION", release.get("JAVA_VERSION", "")).strip('"'),
                      "java-sha256": digest(jdk / "bin/java"), "javac-sha256": digest(jdk / "bin/javac"),
                      "release-sha256": digest(jdk / "release"), "libjvm-sha256": digest(jdk / "lib/server/libjvm.so"),
                      "modules-sha256": digest(jdk / "lib/modules")},
              "dependencies": dependencies, "javac-options": ["-source", "11", "-target", "11"],
              "javac-argfile-sha256": digest(build / "javac.args"),
              "guarded-command-proposal": [str(jdk / "bin/javac"), "@" + str(build / "javac.args")]}
    if basis is not None:
        record["schema"] = "coherent-java-build-plan/2"
        record["dependency-lock-sha256"] = args.expected_dependency_lock_sha256
    (build / "plan.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps({"status": record["status"], "java-sources": len(java_ids), "dependencies": len(dependencies)}))


if __name__ == "__main__":
    main()
