package ansatz.kernel;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;

/**
 * Admission of an exported inductive block (Mathlib store, NDJSON replay). The records only
 * describe the declaration: the inductive rows give each type and the order of its
 * constructors, the constructor rows give the constructor types. That {@link InductiveDecl} is
 * admitted with {@link AddInductive#add}, which generates every constant of the block; then each
 * exported record must equal its generated counterpart — every metadata field, the type and the
 * recursor rules, under Lean's structural equality (binder names and infos ignored) with the
 * universe parameters matched by position — and no record may be missing or extra. The
 * environment returned holds the generated records.
 */
public final class InductiveImport {
    private InductiveImport() {}

    public static Env admit(Env env, InductiveBundle exported, long fuel) {
        InductiveDecl d = declOf(exported);
        Env out = AddInductive.add(env, d, fuel);
        compare(AddInductive.constants(out, d), exported);
        return out;
    }

    /** The declaration an exported block describes: one constructor sequence per type, a bijection with the constructor rows. */
    static InductiveDecl declOf(InductiveBundle b) {
        if (b.inductives.length == 0)
            throw new RuntimeException("invalid inductive block: it must contain at least one inductive type");
        HashMap<Name, ConstantInfo> ctorRows = new HashMap<>();
        for (ConstantInfo c : b.ctors) {
            if (!c.isCtor()) throw new RuntimeException("invalid inductive block: '" + c.name + "' is not a constructor");
            if (ctorRows.put(c.name, c) != null) throw new RuntimeException("invalid inductive block: duplicate constructor record '" + c.name + "'");
        }
        HashSet<Name> listed = new HashSet<>();
        ArrayList<InductiveDecl.Type> types = new ArrayList<>();
        for (ConstantInfo ind : b.inductives) {
            if (!ind.isInduct() || ind.ctors == null)
                throw new RuntimeException("invalid inductive block: '" + ind.name + "' is not an inductive type record");
            ArrayList<InductiveDecl.Constructor> ctors = new ArrayList<>();
            for (Name cn : ind.ctors) {
                ConstantInfo row = ctorRows.get(cn);
                if (row == null)
                    throw new RuntimeException("invalid inductive block: '" + ind.name + "' lists constructor '" + cn + "', which has no record");
                if (!listed.add(cn))
                    throw new RuntimeException("invalid inductive block: constructor '" + cn + "' is listed twice");
                ctors.add(new InductiveDecl.Constructor(cn, row.type));
            }
            types.add(new InductiveDecl.Type(ind.name, ind.type, ctors));
        }
        for (ConstantInfo c : b.ctors)
            if (!listed.contains(c.name))
                throw new RuntimeException("invalid inductive block: constructor record '" + c.name + "' is not listed by any of its inductive types");
        return new InductiveDecl(b.levelParams, b.numParams, b.isUnsafe, types);
    }

    /** One-to-one comparison of the exported records with the generated constants. */
    static void compare(List<ConstantInfo> generated, InductiveBundle b) {
        LinkedHashMap<Name, ConstantInfo> rows = new LinkedHashMap<>();
        for (ConstantInfo[] group : new ConstantInfo[][] {b.inductives, b.ctors, b.recursors})
            for (ConstantInfo ci : group)
                if (rows.put(ci.name, ci) != null) throw new RuntimeException("invalid inductive block: duplicate record '" + ci.name + "'");
        for (ConstantInfo g : generated) {
            ConstantInfo e = rows.remove(g.name);
            if (e == null) throw new RuntimeException("invalid inductive block: missing " + kind(g) + " '" + g.name + "'");
            String field = difference(g, e);
            if (field != null)
                throw new RuntimeException("exported " + kind(g) + " '" + g.name + "' differs from the generated declaration in " + field);
        }
        if (!rows.isEmpty())
            throw new RuntimeException("invalid inductive block: record '" + rows.keySet().iterator().next()
                + "' is not generated by the declaration");
    }

    private static String kind(ConstantInfo ci) {
        return ci.isInduct() ? "inductive type" : ci.isCtor() ? "constructor" : ci.isRecursor() ? "recursor" : "declaration";
    }

    /** The first field in which the exported record differs from the generated one, or null. */
    private static String difference(ConstantInfo g, ConstantInfo e) {
        if (g.tag != e.tag) return "kind";
        if (e.levelParams == null || g.levelParams.length != e.levelParams.length) return "levelParams";
        HashMap<Object, Level> rename = new HashMap<>();
        HashSet<Object> distinct = new HashSet<>();
        for (int i = 0; i < g.levelParams.length; i++) {
            if (!(e.levelParams[i] instanceof Name) || !distinct.add(e.levelParams[i])) return "levelParams";
            if (!g.levelParams[i].equals(e.levelParams[i])) rename.put(g.levelParams[i], Level.param(e.levelParams[i]));
        }
        if (!same(g.type, e.type, rename)) return "type";
        switch (g.tag) {
            case ConstantInfo.INDUCT:
                if (g.numParams != e.numParams) return "numParams";
                if (g.numIndices != e.numIndices) return "numIndices";
                if (!Arrays.equals(g.all, e.all)) return "all";
                if (!Arrays.equals(g.ctors, e.ctors)) return "ctors";
                if (g.numNested != e.numNested) return "numNested";
                if (g.isRec != e.isRec) return "isRec";
                if (g.isReflexive != e.isReflexive) return "isReflexive";
                if (g.isUnsafe != e.isUnsafe) return "isUnsafe";
                return null;
            case ConstantInfo.CTOR:
                if (!g.inductName.equals(e.inductName)) return "inductName";
                if (g.cidx != e.cidx) return "cidx";
                if (g.numParams != e.numParams) return "numParams";
                if (g.numFields != e.numFields) return "numFields";
                if (g.isUnsafe != e.isUnsafe) return "isUnsafe";
                return null;
            case ConstantInfo.RECURSOR:
                if (!Arrays.equals(g.all, e.all)) return "all";
                if (g.numParams != e.numParams) return "numParams";
                if (g.numIndices != e.numIndices) return "numIndices";
                if (g.numMotives != e.numMotives) return "numMotives";
                if (g.numMinors != e.numMinors) return "numMinors";
                if (g.isK != e.isK) return "isK";
                if (g.isUnsafe != e.isUnsafe) return "isUnsafe";
                if (e.rules == null || g.rules.length != e.rules.length) return "rules";
                for (int i = 0; i < g.rules.length; i++) {
                    if (!g.rules[i].ctor.equals(e.rules[i].ctor)) return "rules[" + i + "].ctor";
                    if (g.rules[i].nfields != e.rules[i].nfields) return "rules[" + i + "].nfields";
                    if (!same(g.rules[i].rhs, e.rules[i].rhs, rename)) return "rules[" + i + "].rhs";
                }
                return null;
            default:
                return "kind";
        }
    }

    private static boolean same(Expr generated, Expr exported, HashMap<Object, Level> rename) {
        if (exported == null) return false;
        Expr g = rename.isEmpty() ? generated : Reducer.instantiateLevelParams(generated, rename);
        return LeanExprKey.exprEquals(g, exported);
    }
}
