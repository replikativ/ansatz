(ns ansatz.clj-model.proof
  "Proof support for modelled functions (PR G4).

   The simp set `clj_model` (Lean's `register_simp_attr`, see ansatz.attrs/simp-set): what
   `simp` needs to compute a model on the values the boundary produces.
   - Constructor lemmas, one per op and constructor pattern, generated by kernel evaluation:
     `CljM.lt (vlong i) (vlong j) = some (vbool (decide (i < j)))`, `CljM.add vnil b = none`, …
     Each is `Eq.refl`; its right side is the op's whnf, or, where that leaves a stuck match
     (a `match` on an unknown value), the op unfolded only through definitions that are
     matches. A pattern is refined one argument at a time, only where the op is stuck, so an
     op that ignores an argument gets one lemma for it. Ops are added on demand, from the
     model of the function being proved, so new ops need no lemma code.
     The codecs are ops too: `CljM.encInt n = vlong n` turns an encoded argument into the
     constructor the other lemmas match, `CljM.decInt (vlong i) = some i` reads the result.
   - The codecs' round trips `dec_T (enc_T x) = some x` (`CljM.decInt_encInt`), where `rfl`.
   - The small non-match helpers the right sides use (`CljM.inLong`, `CljM.lres`, …), unfolded,
     and `Int.le a b = (a ≤ b)`, `Int.lt a b = (a < b)` for omega.

   `default-script` is what `(a/conforms f)` runs without tactics: unfold `f.clj`, simp with
   `clj_model`, case-split the `if`s, and close the arithmetic side conditions with omega.
   `port-script` proves `f x… = g x…` for `(a/port f g)` the same way.

   `trust-report` lists what a declaration rests on beyond the kernel: the axioms in its
   dependency closure, and the modelled functions it reaches with their status. A `:tested`
   function is the gap: a proof may unfold it, so the theorem holds of the model, which
   answers d_R where it makes no claim."
  (:require [clojure.string :as str]
            [ansatz.attrs :as attrs]
            [ansatz.state :as state]
            [ansatz.export.writer :as writer]
            [ansatz.kernel.env :as env]
            [ansatz.kernel.expr :as e]
            [ansatz.kernel.level :as lvl]
            [ansatz.kernel.name :as name])
  (:import [ansatz.kernel ConstantInfo Env Name TypeChecker]))

(def simp-set
  "The simp set of the Clojure model."
  "clj_model")

(def helper-defs
  "Model helpers the lemmas' right sides leave folded: plain definitions, not matches, that simp
   unfolds."
  ["CljM.inLong" "CljM.inInt" "CljM.lres" "CljM.lookD" "CljM.found"])

;; ── Constructor lemmas by kernel evaluation ─────────────────────────────────────────────

(defn- nm [s] (name/from-string s))
(defn- const [s] (e/const' (nm s) []))

(defn- strip-lams [x] (if (e/lam? x) (recur (e/lam-body x)) x))

(defn- matcher-name? [s] (boolean (re-find #"\.(match_\d+|casesOn)$" s)))

(defn- cljm? [s] (str/starts-with? s "CljM."))

(defn- unfoldable?
  "A model definition the light evaluation unfolds: a match (its body is a matcher
   application) or an alias of another model constant (`CljM.gt a b := CljM.lt b a`)."
  [^ConstantInfo ci]
  (and (.isDef ci)
       (let [h (e/get-app-fn (strip-lams (.value ci)))
             hn (when (e/const? h) (name/->string (e/const-name h)))]
         (boolean (and hn (or (matcher-name? hn) (cljm? hn)))))))

(defn- delta-allow-set
  "The names the light evaluation may unfold: model matches, aliases and their matchers."
  [^Env env]
  (let [s (java.util.HashSet.)]
    (doseq [^ConstantInfo ci (env/all-constants env)
            :let [n (name/->string (.name ci))]
            :when (and (cljm? n) (or (matcher-name? n) (unfoldable? ci)))]
      (.add s (.name ci)))
    s))

(defn- stuck?
  "Does `x` contain a match, casesOn or recursor (a match on an unknown value, or an unfolded
   `ite`)? Then it is not a usable right side. `Bool.rec` is how `if` is spelled."
  [x]
  (let [found (volatile! false)
        seen (java.util.IdentityHashMap.)]
    (letfn [(walk [x]
              (when-not (or @found (.containsKey seen x))
                (.put seen x true)
                (case (e/tag x)
                  :const (let [n (name/->string (e/const-name x))]
                           (when (and (re-find #"\.(rec|casesOn|match_\d+|brecOn|below)$" n)
                                      (not= n "Bool.rec"))
                             (vreset! found true)))
                  :app (do (walk (e/app-fn x)) (walk (e/app-arg x)))
                  :lam (do (walk (e/lam-type x)) (walk (e/lam-body x)))
                  :forall (do (walk (e/forall-type x)) (walk (e/forall-body x)))
                  ;; a structural recursion's whnf is a projection of its brecOn
                  :proj (walk (e/proj-struct x))
                  :let (do (walk (e/let-type x)) (walk (e/let-value x)) (walk (e/let-body x)))
                  :mdata (walk (e/mdata-expr x))
                  nil)))]
      (walk x))
    @found))

(defn- checker ^TypeChecker [env locals allow]
  (let [tc (TypeChecker. ^Env env)]
    (doseq [[id n ty] locals] (.addLocal tc (long id) ^String n ^ansatz.kernel.Expr ty))
    (when allow (.setTransparency tc 0) (.setDeltaAllowSet tc allow))
    tc))

(def ^:private fresh-local
  "Ids of the locals `normalize` opens binders on (above the ids lemma patterns use)."
  (atom 6000000000))

(defn- normalize
  "whnf by `tc`, then by `light` (model matches only, kept where it gets stuck) in every argument:
   `some (vbool (Bool.not (isNil vnil)))` → `some (vbool (Bool.not true))`."
  [^TypeChecker tc ^TypeChecker light x]
  (let [r (.whnf (.getReducer tc) x)
        r (if (and (identical? tc light) (stuck? r)) x r)
        [h args] (e/get-app-fn-args r)]
    (cond
      (seq args) (apply e/app* h (map #(normalize light light %) args))
      ;; a continuation (`Option.bind m (fun it => …)`): its body, opened on a fresh local
      (e/lam? r) (let [id (swap! fresh-local inc)]
                   (.addLocal light (long id) (str (e/lam-name r)) ^ansatz.kernel.Expr (e/lam-type r))
                   (e/lam (e/lam-name r) (e/lam-type r)
                          (e/abstract1 (normalize light light (e/instantiate1 (e/lam-body r) (e/fvar id))) id)
                          (e/lam-info r)))
      :else r)))

(defn- evaluate
  "The right side for `lhs`, or nil. First `lhs` unfolded only through model matches and aliases
   (it keeps the source's spelling: `i < j`, `CljM.lres (i + j)`); where that is stuck, its
   whnf (`CljM.eq` goes through fuel and `Option.bind`). Either must be free of stuck matches.
   `last?` (the pattern cannot be refined further): finally the op itself unfolded once, its
   arguments as before. An op that wraps another (`CljM.first v := Option.bind (CljM.oelems v)
   …`) is neither a match nor an alias, and its whnf is stuck where the wrapped op matches on an
   unknown field (`vlseq b c`, a chain of unknown length)."
  [env locals allow lhs last?]
  (let [light (checker env locals allow)
        h (e/get-app-fn lhs)
        self (when (and last? (e/const? h))
               (doto (java.util.HashSet. ^java.util.Collection allow) (.add (e/const-name h))))]
    (some (fn [[tc args-tc]] (let [r (normalize tc args-tc lhs)]
                               (when (and (not= r lhs) (not (stuck? r))) r)))
          (cond-> [[light light] [(checker env locals nil) light]]
            self (conj [(checker env locals self) light])))))

(defn- field-types [env ctor]
  (loop [t (.type ^ConstantInfo (env/lookup! env (nm ctor))) acc []]
    (if (e/forall? t) (recur (e/forall-body t) (conj acc (e/forall-type t))) acc)))

(def refinable-types
  "The inductives whose constructors a lemma pattern enumerates: the model's universe and the
   DSL `Value` (the boundary's dynamic type)."
  #{"CljM.V" "Value"})

(defn- refinable [env ty]
  (when (e/const? ty)
    (let [n (name/->string (e/const-name ty))]
      (when (and (refinable-types n) (env/lookup env (nm n))) n))))

(defn- theorem-of
  "`∀ locals, lhs = rhs` by `Eq.refl`, as a kernel theorem `thm-name`."
  [env locals lhs rhs thm-name]
  (let [tc (checker env locals nil)
        ty (.inferType tc lhs)
        u (e/sort-level (.whnf (.getReducer tc) (.inferType tc ty)))
        ids (mapv first locals)
        close (fn [body mk] (reduce (fn [b [_ n t]] (mk n t b)) (e/abstract-many body ids) (rseq locals)))
        stmt (close (e/app* (e/const' (nm "Eq") [u]) ty lhs rhs) (fn [n t b] (e/forall' n t b :default)))
        proof (close (e/app* (e/const' (nm "Eq.refl") [u]) ty lhs) (fn [n t b] (e/lam n t b :default)))]
    (env/mk-thm (nm thm-name) [] stmt proof)))

(defn- op-lemmas
  "Constructor lemmas for the model op `op`: [[name ConstantInfo] …]. Starts from the op on
   free arguments and, while the evaluation is stuck, refines the first free argument of a
   `refinable-types` type into each of its constructors, at most `depth` arguments deep."
  [env allow op depth]
  (let [ptys (loop [t (.type ^ConstantInfo (env/lookup! env (nm op))) acc []]
               (if (e/forall? t) (recur (e/forall-body t) (conj acc (e/forall-type t))) acc))
        next-id (let [c (atom 4000000)] #(swap! c inc))
        free (fn [ty i] (let [id (next-id)]
                          {:locals [[id (str "a" i) ty]] :e (e/fvar id) :type (refinable env ty) :tag "x"}))
        ctor-arg (fn [^Name ctor]
                   (let [fts (field-types env (name/->string ctor))
                         ids (vec (repeatedly (count fts) next-id))]
                     {:locals (mapv (fn [id t i] [id (str "f" i) t]) ids fts (range))
                      :e (apply e/app* (e/const' ctor []) (map e/fvar ids))
                      :tag (last (str/split (name/->string ctor) #"\."))}))
        out (volatile! [])]
    (letfn [(go [args depth]
                (let [locals (vec (mapcat :locals args))
                      lhs (apply e/app* (const op) (map :e args))]
                  (if-let [rhs (evaluate env locals allow lhs
                                         (not (and (pos? depth) (some :type args))))]
                    (let [thm (str op ".ctor_" (str/join "_" (map :tag args)))]
                      (vswap! out conj [thm (theorem-of env locals lhs rhs thm)]))
                    (when-let [p (and (pos? depth) (first (keep-indexed (fn [i a] (when (:type a) i)) args)))]
                      (doseq [ctor (.ctors ^ConstantInfo (env/lookup! env (nm (:type (nth args p)))))]
                        (go (assoc args p (ctor-arg ctor)) (dec depth)))))))]
      (go (vec (map-indexed (fn [i t] (free t i)) ptys)) depth))
    @out))

(defn- fix-op?
  "A fixpoint combinator `CljM.fix<k>` (G3): it matches on its Nat fuel, not on a value, so
   constructor lemmas do not apply (a proof unfolds it at a successor fuel)."
  [op]
  (boolean (re-matches #"CljM\.fix\d+" op)))

(defn- recursive-op?
  "A structurally recursive model definition (it has smart unfolding, `op._sunfold`)."
  [env op]
  (some? (env/lookup env (nm (str op "._sunfold")))))

(defn- equation-lemmas
  "The equation lemmas `op.eq_1` … of a recursive op, one per constructor pattern (Lean's
   `f.eq_<n>`). Evaluating such an op on a pattern with a free argument unfolds its recursion
   into the brecOn encoding, which is no usable right side; its equations are what simp uses
   for a recursive definition in Lean."
  [env op]
  (vec (take-while #(env/lookup env (nm %)) (map #(str op ".eq_" %) (iterate inc 1)))))

(defn ensure-op-lemmas!
  "Install the constructor lemmas of the model ops `ops` (names) not yet done, and add them to
   the `clj_model` simp set. Ops already handled are recorded in the :clj-model-lemmas
   extension, so each op is evaluated once per environment. A recursive op (`recursive-op?`)
   contributes its equation lemmas instead."
  [ops]
  (locking #'ensure-op-lemmas!
    (let [done (env/get-extension @state/ansatz-env :clj-model-lemmas {})
          todo (remove #(or (contains? done %) (fix-op? %)) (distinct ops))]
      (when (seq todo)
        (let [env @state/ansatz-env
              allow (delta-allow-set env)
              {rec true plain false} (group-by #(recursive-op? env %) todo)
              made (into {} (map (fn [op] [op (op-lemmas env allow op 2)])) plain)
              eqns (into {} (map (fn [op] [op (equation-lemmas env op)])) rec)]
          (swap! state/ansatz-env
                 (fn [env]
                   (as-> env env
                     (reduce (fn [env [op ls]]
                               (-> (reduce (fn [env [_ ci]] (env/check-constant env ci)) env ls)
                                   (attrs/add-to-simp-set simp-set (map first ls))
                                   (env/update-extension :clj-model-lemmas {} assoc op (mapv first ls))))
                             env made)
                     (reduce (fn [env [op ls]]
                               (-> (attrs/add-to-simp-set env simp-set ls)
                                   (env/update-extension :clj-model-lemmas {} assoc op ls)))
                             env eqns))))))
      (select-keys (env/get-extension @state/ansatz-env :clj-model-lemmas {}) ops))))

(defn model-ops
  "The model constants (`CljM.*`) a declaration's type, or a definition's value, mentions."
  [env decl]
  (let [out (java.util.LinkedHashSet.)
        seen (java.util.IdentityHashMap.)]
    (letfn [(walk [x]
              (when-not (.containsKey seen x)
                (.put seen x true)
                (case (e/tag x)
                  :const (let [n (name/->string (e/const-name x))]
                           (when (and (cljm? n) (not= n "CljM.V") (not (str/starts-with? n "CljM.V."))) (.add out n)))
                  :app (do (walk (e/app-fn x)) (walk (e/app-arg x)))
                  :lam (do (walk (e/lam-type x)) (walk (e/lam-body x)))
                  :forall (do (walk (e/forall-type x)) (walk (e/forall-body x)))
                  :let (do (walk (e/let-type x)) (walk (e/let-value x)) (walk (e/let-body x)))
                  nil)))]
      (let [ci ^ConstantInfo (env/lookup! env (nm (str decl)))]
        (walk (.type ci))
        (when (.isDef ci) (walk (.value ci)))))
    (vec out)))

(defn user-model-defs
  "The definitions of modelled Clojure functions (ansatz.clj-model.callees: `clj.<ns>.<name>.…`)
   that the declaration `decl` reaches, for a proof to unfold."
  [env decl]
  (if-not (env/lookup env (nm (str decl)))
    []
    (vec (keep (fn [^ConstantInfo ci]
                 (let [n (name/->string (.name ci))]
                   (when (and (str/starts-with? n "clj.") (.isDef ci)) n)))
               (writer/closure-constants env [(str decl)])))))

(defn ensure-lemmas!
  "The constructor lemmas `decl` needs: those of the model ops its value (and the modelled
   functions it calls, `user-model-defs`) mentions, and of the ops their right sides mention,
   transitively; plus `extra-ops` (e.g. the result decoder). Returns the op names."
  [decl extra-ops]
  (loop [todo (into (vec extra-ops)
                    (mapcat #(model-ops @state/ansatz-env %)
                            (cons decl (user-model-defs @state/ansatz-env decl))))
         seen #{}]
    (let [new (remove seen todo)]
      (if (empty? new)
        (vec seen)
        (let [made (ensure-op-lemmas! new)
              env @state/ansatz-env
              rhs-ops (mapcat (fn [thm] (model-ops env thm)) (mapcat val made))]
          (recur (vec rhs-ops) (into seen new)))))))

;; ── The default conformance script ──────────────────────────────────────────────────────

(def case-split-types
  "Parameter types the default script case-splits first, so the encoder meets a constructor:
   `Value` (its `CljM.ofValue` is a match on the value)."
  #{'Value})

(defn- parameter-split
  "The first tactic for a parameter of type `t`: cases for `case-split-types` and the G2 codecs'
   `Prod`/`Option` (their encoder is a match on the value), induction for `List` (its encoder
   recurses over the list, and so does a model that walks the encoded chain), nil otherwise.
   For a recursive model (`rec?`) a `List` is only case-split: the recursion is argued by
   ansatz.clj-model.recursion, whose templates read the list's head and tail."
  [p t rec?]
  (let [head (if (seq? t) (first t) t)]
    (cond (case-split-types t) (list 'cases p)
          (= 'List head) (list (if rec? 'cases 'induction) p)
          (#{'Prod 'Option} head) (list 'cases p))))

(defn- spelling-lemmas
  "`Int.le a b = (a ≤ b)` and `Int.lt a b = (a < b)` (`Eq.refl`): a comparison in a Bool
   position elaborates to `decide (Int.le a b)`; after these, simp turns a branch condition
   `decide (a ≤ b) = true` into the `a ≤ b` omega reads."
  [env]
  (let [int (const "Int")
        [a b] [[1 "a" int] [2 "b" int]]
        args [(e/fvar 1) (e/fvar 2)]]
    (for [[op cls inst thm] [["Int.le" "LE.le" "Int.instLEInt" "CljM.Int_le"]
                             ["Int.lt" "LT.lt" "Int.instLTInt" "CljM.Int_lt"]]]
      [thm (theorem-of env [a b] (apply e/app* (const op) args)
                       (apply e/app* (e/const' (nm cls) [lvl/zero]) int (const inst) args) thm)])))

(defn- dec-enc-lemma
  "`dec (enc x) = some x` (`Eq.refl`) for a codec, as [name ConstantInfo]: `CljM.decInt_encInt`.
   It holds by computation for the scalar codecs; the `Value` codec's round trip is not the
   identity (map entries are deduplicated, a map over 8 entries has no claim)."
  [env {:keys [enc dec]}]
  (let [ty (e/forall-type (.type ^ConstantInfo (env/lookup! env (nm enc))))
        thm (str dec "_" (last (str/split enc #"\.")))]
    [thm (theorem-of env [[1 "x" ty]] (e/app (const dec) (e/app (const enc) (e/fvar 1)))
                     (e/app* (e/const' (nm "Option.some") [lvl/zero]) ty (e/fvar 1)) thm)]))

(defn- add-lemmas!
  "Check the [name ConstantInfo] lemmas not yet in the env and add them to `clj_model`; a lemma
   the kernel rejects is left out (`dec-enc-lemma` of a codec whose round trip is not `rfl`)."
  [lemmas]
  (swap! state/ansatz-env
         (fn [env]
           (reduce (fn [env [n ci]]
                     (if (env/lookup env (nm n))
                       env
                       (if-let [env' (try (env/check-constant env ci) (catch Exception _ nil))]
                         (attrs/add-to-simp-set env' simp-set [n])
                         env)))
                   env lemmas))))

(defn prepare!
  "Make the `clj_model` simp set ready for a proof about the model `model-name` whose arguments
   cross the boundary by `codecs` and whose result by `ret-codec` (ansatz.clj-model.boundary/
   codec maps): the constructor lemmas of every op involved (an encoder's lemma unfolds it to
   its constructor), the codecs' `dec (enc x) = some x`, the helpers and the spelling lemmas."
  [model-name codecs ret-codec]
  (locking #'ensure-op-lemmas!
    (swap! state/ansatz-env attrs/add-to-simp-set simp-set helper-defs)
    (let [env @state/ansatz-env]
      (add-lemmas! (concat (spelling-lemmas env)
                           (map #(dec-enc-lemma env %) (distinct (conj (vec codecs) ret-codec)))))))
  (ensure-lemmas! model-name (conj (mapv :enc codecs) (:dec ret-codec))))

(defn with-deep-stack
  "Run `f` (with the caller's bindings) on a thread with a 64 MB stack; return its value or
   rethrow. simp and the kernel recurse over the nested binds and branches of a model: deep but
   finite, and on a JIT-cold JVM the default stack overflowed for `(if (and (< x 1000)
   (> x -1000)) (inc x) x)` (a 1 GB stack proves it in 3 s)."
  [f]
  (let [p (promise)
        t (Thread. nil (bound-fn [] (deliver p (try {:v (f)} (catch Throwable x {:ex x}))))
                   "clj-model-proof" (long (* 64 1024 1024)))]
    (.start t)
    (let [{:keys [v ex]} @p]
      (if ex (throw ex) v))))

(defn compute-script
  "Case-split `pairs`' `case-split-types` parameters, simp with `unfold` and `clj_model`, then
   repeatedly split the `if`s and simp each branch with its conditions (simp_all, which also
   turns them into the comparisons omega reads; a branch can expose a further `if`), omega.
   `rec?`: see `parameter-split`."
  ([pairs unfold] (compute-script pairs unfold false))
  ([pairs unfold rec?]
   (let [s (symbol simp-set)]
     (vec (concat (keep (fn [[p t]] (parameter-split p t rec?)) pairs)
                  [(list 'all_goals (list 'simp (conj (vec unfold) s)))
                   ;; a recursive model's entry can apply a modelled function only once a branch
                   ;; is split (`(Option.bind (dite …) g)`), so its branches unfold them too
                   (list 'repeat '(any_goals (split_ifs))
                         (list 'all_goals (list 'try (list 'simp_all (if rec? (conj (vec unfold) s) [s])))))
                   '(all_goals (try (omega)))])))))

(defn model-unfold
  "The definitions a proof about `f` unfolds: its model `f.clj` and the modelled functions it
   calls (a recursive group's functional among them)."
  [f]
  (map symbol (cons (str f ".clj") (user-model-defs @state/ansatz-env (str f ".clj")))))

(defn recursive-model?
  "Does the model of `f` (or a modelled function it calls) enter a recursive group?"
  [f]
  (let [env @state/ansatz-env
        n (str f ".clj")]
    (boolean (some fix-op? (mapcat #(model-ops env %) (cons n (user-model-defs env n)))))))

(defn default-script
  "The tactics `(a/conforms f)` runs when given none, for `f` with parameters `pairs`
   ([[sym type] …]): case-split `case-split-types` parameters, unfold the model `f.clj` (and the
   modelled functions it calls) and compute it with `clj_model` (the constructor lemmas fire on
   the encoded arguments), case-split every `if` the computation could not decide, finish each
   branch with simp_all, and close the arithmetic side conditions (long overflow against the
   declared types) with omega. A recursive model is proved by ansatz.clj-model.recursion
   (boundary/prove-conforms! dispatches on `recursive-model?`)."
  [f pairs]
  (compute-script pairs (model-unfold f)))

(defn port-script
  "The tactics `(a/port f g)` runs when given none, proving `f x… = g x…`: the conformance
   computation with `f` (its defining equation), its model and `g` unfolded."
  [f g pairs]
  (compute-script pairs [(symbol (str f)) (symbol (str f ".clj")) (symbol (str g))]))

;; ── Trust report ────────────────────────────────────────────────────────────────────────

(def standard-axioms
  "Lean's axioms: what every Mathlib proof may rest on."
  #{"propext" "Quot.sound" "Classical.choice"})

(defn trust-report
  "What the declaration `decl` rests on beyond the kernel, from its dependency closure:
   {:declaration, :axioms {:standard […] :other […]} (`:other` holds every other axiom: an
   `a/foreign` function, a `^:partial` definition, `sorryAx`, an opaque callee), :modelled
   {f status} for the `a/foreign ^:model` functions reached, :tested [f …], those still
   `:tested`, and :opaque [g …], the Clojure functions a model calls without modelling them
   (ansatz.clj-model.callees: each an axiom assuming `g` is pure). A `:tested` function is a
   definition a proof may unfold, so a theorem through it holds of the model, which answers the
   default d_R where it makes no claim; `:proved` and `:ported` close that. An opaque callee
   stays an assumption at every status."
  ([decl] (trust-report @state/ansatz-env decl))
  ([env decl]
   (let [cis (writer/closure-constants env [(str decl)])
         names (map #(name/->string (.name ^ConstantInfo %)) cis)
         axioms (sort (keep (fn [^ConstantInfo ci] (when (.isAxiom ci) (name/->string (.name ci)))) cis))
         statuses (env/get-extension env :clj-model {})
         modelled (into (sorted-map) (keep (fn [n] (when-let [{:keys [status]} (get statuses n)] [n status]))) names)
         opaque (env/get-extension env :clj-model-opaque {})]
     {:declaration (str decl)
      :axioms {:standard (filterv standard-axioms axioms) :other (filterv (complement standard-axioms) axioms)}
      :modelled modelled
      :tested (vec (keep (fn [[n st]] (when (= :tested st) n)) modelled))
      :opaque (vec (sort (distinct (keep opaque axioms))))})))
